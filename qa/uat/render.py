"""Render the UAT catalogue into `UAT_SCRIPT.md` (CR263).

`UAT_SCRIPT.md` is generated, never hand-edited — edit `cases/<area>.yaml` and
re-run this. `--check` exits 1 when the committed script is stale; the offline
guard calls it so a catalogue edit without a re-render fails the build.

    python qa/uat/render.py           # write
    python qa/uat/render.py --check   # verify
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from catalogue import UAT_ROOT, Area, Case, load  # noqa: E402

SCRIPT_PATH = UAT_ROOT / "UAT_SCRIPT.md"

_LAYER_LABEL = {
    "api": "API (automated, live Alpha)",
    "device": "Device (automated, Appium)",
    "manual": "Manual (iPhone checklist)",
}


def _case_md(c: Case) -> list[str]:
    tags = [_LAYER_LABEL[c.layer], "plans: " + ", ".join(c.plans)]
    if c.platforms:
        tags.append("platforms: " + ", ".join(c.platforms))
    if c.llm:
        tags.append("uses LLM")
    if c.status == "blocked":
        tags.append(f"**BLOCKED** — {c.blocked_on}")
    out = [f"#### {c.id} — {c.title}", "", "_" + " · ".join(tags) + "_", ""]
    if c.preconditions:
        out.append("**Preconditions**")
        out += [f"{i}. {p}" for i, p in enumerate(c.preconditions, 1)]
        out.append("")
    out.append("**Steps**")
    out += [f"{i}. {s}" for i, s in enumerate(c.steps, 1)]
    out += ["", "**Expected**"]
    out += [f"{i}. {e}" for i, e in enumerate(c.expected, 1)]
    if c.notes:
        out += ["", f"> {c.notes}"]
    out.append("")
    return out


def render(areas: list[Area]) -> str:
    cases = [c for a in areas for c in a.cases]
    by_layer = {layer: sum(1 for c in cases if c.layer == layer) for layer in _LAYER_LABEL}
    blocked = sum(1 for c in cases if c.status == "blocked")
    lines = [
        "<!-- GENERATED by qa/uat/render.py from qa/uat/cases/*.yaml — do not hand-edit. -->",
        "# AMI Trade — Whole-App UAT Script",
        "",
        "Source of truth: `qa/uat/cases/*.yaml` (CR263). Automated cases run via",
        "`scripts/uat/run_uat.sh`; manual cases are the iPhone checklist at the end.",
        "",
        f"**{len(cases)} cases** — "
        + ", ".join(f"{n} {layer}" for layer, n in by_layer.items())
        + f"; {blocked} blocked.",
        "",
        "## Areas",
        "",
    ]
    for i, a in enumerate(areas, 1):
        lines.append(f"{i}. [{a.title}](#{a.area.replace('_', '-')}) — {len(a.cases)} cases")
    lines.append("")

    for a in areas:
        lines += [f"<a id=\"{a.area.replace('_', '-')}\"></a>", f"## {a.title}", ""]
        if a.summary:
            lines += [a.summary.strip(), ""]
        for layer in ("api", "device"):
            group = [c for c in a.cases if c.layer == layer]
            if group:
                lines += [f"### {_LAYER_LABEL[layer]}", ""]
                for c in group:
                    lines += _case_md(c)

    manual = [(a, c) for a in areas for c in a.cases if c.layer == "manual"]
    lines += ["## Manual — iPhone checklist", ""]
    if not manual:
        lines += ["_None._", ""]
    for _, c in manual:
        lines += _case_md(c)
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render(load())
    if "--check" in argv:
        current = SCRIPT_PATH.read_text() if SCRIPT_PATH.exists() else ""
        if current != text:
            print("UAT_SCRIPT.md is stale — run: python qa/uat/render.py")
            return 1
        print("UAT_SCRIPT.md is fresh")
        return 0
    SCRIPT_PATH.write_text(text)
    print(f"wrote {SCRIPT_PATH.relative_to(UAT_ROOT.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
