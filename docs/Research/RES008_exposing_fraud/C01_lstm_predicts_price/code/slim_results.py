"""
Write the committed out/results.json from the full run output.

run_c01.py stores, for every ticker-seed cell, the model's and buy-and-hold's
daily return series plus their dates (M4). That is ~27 MB across 120 cells, too
large for the repo, and nothing in RESULTS.md quotes a single day. This script
replaces each cell's series with the summary figures the write-up does quote and
leaves every pooled interval untouched. The full file stays on disk as
out/results_full.json (git-ignored; regenerated by run_c01.py).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

OUT_DIR = Path(__file__).resolve().parent.parent / "out"
ARMS = ("A1", "A2", "B-price", "B-return")


def summarise_m4(series: dict) -> dict:
    model = np.asarray(series["model_daily_returns"], dtype=np.float64)
    bh = np.asarray(series["bh_daily_returns"], dtype=np.float64)
    return {
        "first_date": series["dates"][0],
        "last_date": series["dates"][-1],
        "n_days": int(len(model)),
        "model_mean_daily_return": float(model.mean()),
        "bh_mean_daily_return": float(bh.mean()),
        "model_total_return": float(np.prod(1.0 + model) - 1.0),
        "bh_total_return": float(np.prod(1.0 + bh) - 1.0),
        "share_of_days_with_nonzero_model_return": float(np.mean(model != 0.0)),
    }


def main() -> None:
    full = json.loads((OUT_DIR / "results_full.json").read_text())
    for arm in ARMS:
        for cell in full[arm]["per_ticker_seed"]:
            cell["M4"] = {execution: summarise_m4(series) for execution, series in cell["M4"].items()}
    full["meta"]["note"] = (
        "Per-cell M4 daily series replaced by summaries (code/slim_results.py); "
        "pooled intervals were computed from the full series."
    )
    (OUT_DIR / "results.json").write_text(json.dumps(full, indent=2) + "\n")
    print(f"Wrote out/results.json ({(OUT_DIR / 'results.json').stat().st_size / 1e3:.0f} KB)")


if __name__ == "__main__":
    main()
