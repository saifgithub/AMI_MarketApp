def test_t_eff_direct_sum_matches_the_closed_form() -> None:
    """The module computes the direct sum; the closed form is the independent
    check. A formula that checks itself checks nothing."""
    for lam in (0.90, 0.94, 0.97, 0.98):
        for t in (1, 2, 5, 63, 126, 252, 504):
            closed = ((1.0 + lam) / (1.0 - lam)) * (
                (1.0 - lam ** t) / (1.0 + lam ** t)
            )
            assert abs(t_eff(lam, t) - closed) < 1e-9, (lam, t)


