# ── 20. Package contract ────────────────────────────────────────────────────


def test_stdlib_purity_guard() -> None:
    """`trading_math` is copy-portable by contract: stdlib only, no `app`
    imports, no numpy. Asserted structurally rather than trusted, because the
    contract is a comment in `__init__.py` and comments do not fail builds."""
    from app.trading_math import portfolio_risk

    source = Path(portfolio_risk.__file__).read_text()
    tree = ast.parse(source)
    imported: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level > 0:          # relative — inside the package, allowed
                continue
            imported.append(node.module or "")

    assert imported, "vacuity guard — the parse found no imports at all"
    for name in imported:
        root = name.split(".")[0]
        assert root in {"math", "__future__"}, f"disallowed import: {name}"
    assert not any(n.startswith("numpy") for n in imported)
    assert not any(n.startswith("app") for n in imported)


def test_no_shrinkage_anywhere() -> None:
    """Rev 4 estimator pin 1 removed Ledoit–Wolf entirely — not disabled, not
    stubbed. It suppressed the correlated-cluster alarm this feature exists to
    raise (89.0% of windows fired unshrunk vs 30.1% shrunk) and divided by zero
    on a cash row."""
    from app.trading_math import portfolio_risk

    tree = ast.parse(Path(portfolio_risk.__file__).read_text())

    # Every identifier the module actually defines or references, from the AST —
    # so the prose that explains WHY shrinkage is absent cannot trip the guard,
    # and no amount of rephrasing that prose can weaken it either.
    identifiers: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            identifiers.append(node.name)
        elif isinstance(node, ast.Name):
            identifiers.append(node.id)
        elif isinstance(node, ast.Attribute):
            identifiers.append(node.attr)
        elif isinstance(node, ast.arg):
            identifiers.append(node.arg)

    assert identifiers, "vacuity guard — the parse found no identifiers at all"
    assert "ewma_covariance" in identifiers, "vacuity guard — wrong module parsed"
    for name in identifiers:
        lowered = name.lower()
        assert "shrink" not in lowered, name
        assert "ledoit" not in lowered, name
        assert "lw_" not in lowered, name
