#!/usr/bin/env bash
# Install (or remove with --uninstall) the 03:00 nightly UAT LaunchAgent (CR263).
#
# launchd runs a missed StartCalendarInterval job at next wake, so a sleeping
# Mac runs it late rather than never. To have it run AT 03:00, also schedule a
# wake (needs sudo, so it is printed, not run):
#     sudo pmset repeat wakeorpoweron MTWRFSU 02:55:00
# The external "Extreme Pro" volume must be mounted and Saiful logged in (the
# Simulator needs a GUI session).
#
# Why a launcher in ~/Library and a Terminal window: macOS privacy (TCC) blocks
# a launchd-spawned /bin/bash from reading a removable volume ("Operation not
# permitted", measured 2026-10-19). Terminal.app already holds that grant, so
# launchd runs a tiny launcher from the home folder that asks Terminal to run
# nightly.sh — the same pattern as com.amitrade.dailycheckin.

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LABEL="ai.agenticmarketintel.uat-nightly"
PLIST="${HOME}/Library/LaunchAgents/${LABEL}.plist"
LOG_DIR="${HOME}/Library/Logs/ami-uat"
SUPPORT="${HOME}/Library/Application Support/ami-uat"
LAUNCHER="${SUPPORT}/launch_nightly.sh"

if [[ "${1:-}" == "--uninstall" ]]; then
  launchctl bootout "gui/$(id -u)/${LABEL}" 2>/dev/null || true
  rm -f "$PLIST" "$LAUNCHER"
  echo "removed ${LABEL}"
  exit 0
fi

mkdir -p "$LOG_DIR" "$SUPPORT" "$(dirname "$PLIST")"
cat > "$LAUNCHER" <<LAUNCH
#!/bin/bash
# Generated by ${PROJECT_ROOT}/scripts/uat/install_nightly.sh (CR263).
osascript <<'APPLESCRIPT'
tell application "Terminal"
    do script "'${PROJECT_ROOT}/scripts/uat/nightly.sh' >> '${LOG_DIR}/nightly.log' 2>&1; exit"
end tell
APPLESCRIPT
LAUNCH
chmod +x "$LAUNCHER"
cat > "$PLIST" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${LABEL}</string>
    <key>ProgramArguments</key>
    <array>
        <string>${LAUNCHER}</string>
    </array>
    <key>StartCalendarInterval</key>
    <dict>
        <key>Hour</key>
        <integer>3</integer>
        <key>Minute</key>
        <integer>0</integer>
    </dict>
    <key>RunAtLoad</key>
    <false/>
    <key>StandardOutPath</key>
    <string>${LOG_DIR}/launcher.log</string>
    <key>StandardErrorPath</key>
    <string>${LOG_DIR}/launcher.err.log</string>
</dict>
</plist>
PLIST
plutil -lint "$PLIST"
launchctl bootout "gui/$(id -u)/${LABEL}" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
echo "installed ${LABEL} — 03:00 daily, logs in ${LOG_DIR}"
echo "run now:  launchctl kickstart gui/$(id -u)/${LABEL}"
echo "wake Mac: sudo pmset repeat wakeorpoweron MTWRFSU 02:55:00"
